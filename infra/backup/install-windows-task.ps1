<#
.SYNOPSIS
    G6 · 个人使用：一键注册 Windows 计划任务，每天自动备份 dev.db.

.DESCRIPTION
    给 dev 模式的个人用户准备的"开箱即用"备份方案。
    自动注册一个 Windows Scheduled Task，每天 02:00 跑一次 backup.py，
    输出到 ./backups/，按 daily 策略保留 7 份。

    脚本只需要跑一次。注册后 Windows 会自己每天定时执行，机器关机
    错过的次数最多重补一次。

.PARAMETER ProjectRoot
    项目根目录的绝对路径（默认 = 此脚本所在目录的上两级）

.PARAMETER PythonExe
    Python 解释器路径（默认 = py，使用 PATH 上的 python launcher）

.PARAMETER TaskTime
    每天触发时间，格式 HH:mm（默认 02:00）

.PARAMETER TaskName
    任务名（默认 ROS_DailyBackup）

.PARAMETER WeeklyAlso
    若指定，额外注册一个每周一 03:00 的 weekly 备份任务（保留 4 份）

.EXAMPLE
    # 默认安装
    powershell -ExecutionPolicy Bypass -File infra\backup\install-windows-task.ps1

    # 指定 Python 路径
    powershell -ExecutionPolicy Bypass -File infra\backup\install-windows-task.ps1 -PythonExe "D:\Programs\Python313\python.exe"

    # 同时注册 weekly 任务
    powershell -ExecutionPolicy Bypass -File infra\backup\install-windows-task.ps1 -WeeklyAlso

.NOTES
    需要管理员权限注册任务。如果脚本提示权限不足，右键 PowerShell → 以管理员身份运行。
    卸载：Unregister-ScheduledTask -TaskName "ROS_DailyBackup" -Confirm:$false
#>
param(
    [string]$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path,
    [string]$PythonExe = "py",
    [string]$TaskTime = "02:00",
    [string]$TaskName = "ROS_DailyBackup",
    [switch]$WeeklyAlso
)

$ErrorActionPreference = "Stop"

# ── 校验 ──
if (-not (Test-Path $ProjectRoot)) {
    Write-Error "ProjectRoot does not exist: $ProjectRoot"
    exit 1
}
$BackupScript = Join-Path $ProjectRoot "infra\backup\backup.py"
if (-not (Test-Path $BackupScript)) {
    Write-Error "backup.py not found at: $BackupScript"
    exit 1
}

Write-Host "=== ROS Backup Task Installer ===" -ForegroundColor Cyan
Write-Host "Project root : $ProjectRoot"
Write-Host "Python       : $PythonExe"
Write-Host "Backup script: $BackupScript"
Write-Host "Daily time   : $TaskTime"
Write-Host ""

# ── 注册 daily 任务 ──
function Register-DailyBackup {
    param([string]$Name, [string]$Type, [string]$Time, [string]$DayOfWeek = $null)

    $action = New-ScheduledTaskAction `
        -Execute $PythonExe `
        -Argument "`"$BackupScript`" --type $Type --quiet" `
        -WorkingDirectory $ProjectRoot

    if ($DayOfWeek) {
        $trigger = New-ScheduledTaskTrigger -Weekly -DaysOfWeek $DayOfWeek -At $Time
    } else {
        $trigger = New-ScheduledTaskTrigger -Daily -At $Time
    }

    # StartWhenAvailable: 错过触发时（关机）会在下次开机后立即重补
    # MultipleInstances: 防止上次还没跑完时重复触发
    # ExecutionTimeLimit: 4h 上限（远超实际所需），防止僵尸任务永久占用
    $settings = New-ScheduledTaskSettingsSet `
        -StartWhenAvailable `
        -MultipleInstances IgnoreNew `
        -ExecutionTimeLimit (New-TimeSpan -Hours 4)

    $description = "ROS daily backup ($Type) of dev.db + uploads/ to ./backups/. Generated by infra/backup/install-windows-task.ps1"

    if (Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue) {
        Write-Host "  -> Task '$Name' already exists, updating..." -ForegroundColor Yellow
        Unregister-ScheduledTask -TaskName $Name -Confirm:$false
    }

    Register-ScheduledTask `
        -TaskName $Name `
        -Action $action `
        -Trigger $trigger `
        -Settings $settings `
        -Description $description `
        -RunLevel Limited | Out-Null

    Write-Host "  [OK] Registered '$Name' ($Type @ $Time$(if($DayOfWeek){" $DayOfWeek"}))" -ForegroundColor Green
}

try {
    Register-DailyBackup -Name $TaskName -Type "daily" -Time $TaskTime

    if ($WeeklyAlso) {
        $weeklyTime = "03:00"
        Register-DailyBackup -Name "$($TaskName)_Weekly" -Type "weekly" -Time $weeklyTime -DayOfWeek "Monday"
    }

    Write-Host ""
    Write-Host "✓ Installation complete." -ForegroundColor Green
    Write-Host ""
    Write-Host "Verify with:" -ForegroundColor Cyan
    Write-Host "  Get-ScheduledTask -TaskName '$TaskName*' | Format-Table TaskName, State, Triggers"
    Write-Host ""
    Write-Host "Run once now (sanity check):" -ForegroundColor Cyan
    Write-Host "  Start-ScheduledTask -TaskName '$TaskName'"
    Write-Host ""
    Write-Host "Uninstall:" -ForegroundColor Cyan
    Write-Host "  Unregister-ScheduledTask -TaskName '$TaskName' -Confirm:`$false"
    if ($WeeklyAlso) {
        Write-Host "  Unregister-ScheduledTask -TaskName '$($TaskName)_Weekly' -Confirm:`$false"
    }
}
catch {
    Write-Host ""
    Write-Error "Installation failed: $_"
    Write-Host "Common issues:" -ForegroundColor Yellow
    Write-Host "  - Need admin: right-click PowerShell -> Run as Administrator"
    Write-Host "  - Python launcher 'py' not found: pass -PythonExe 'C:\path\to\python.exe'"
    exit 2
}
